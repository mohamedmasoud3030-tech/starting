#!/usr/bin/env node
/**
 * Migration immutability — applied migrations are eternal.
 *
 * Compares every migration file's SHA-256 against the committed hashes in
 * guardian/contract/migration-hashes.json. Editing an applied migration is a
 * CRITICAL finding: the fix must always be a NEW migration.
 */
import { join } from "node:path";
import { hashFile, migrationFiles, readJson, CONTRACT_DIR, MIGRATIONS_DIR } from "../../lib/common.mjs";

export const id = "G-MIGRATION-IMMUTABILITY";
export const title = "Applied migrations must never be edited (immutability)";
export const category = "migrations";
export const defaultSeverity = "CRITICAL";
export const mode = "static";

export async function run(ctx) {
  const { report } = ctx;
  const hashesPath = join(CONTRACT_DIR, "migration-hashes.json");
  let baseline;
  try {
    baseline = readJson(hashesPath);
  } catch {
    if (ctx.cli.snapshot) {
      report.pass(this, `${id}-NO-BASELINE`, "migration-hashes.json will be generated by this snapshot run", `${hashesPath} not found (snapshot mode)`);
    } else {
      report.fail(this, {
        severity: "HIGH",
        id: `${id}-NO-BASELINE`,
        title: "migration-hashes.json is missing — run `npm run db:guardian:snapshot`",
        evidence: `${hashesPath} not found`,
      });
    }
    return;
  }
  const baselineFiles = new Set(Object.keys(baseline.files ?? {}));
  const current = migrationFiles();
  let edited = 0;
  let added = 0;
  const editedList = [];

  for (const f of current) {
    const h = hashFile(join(MIGRATIONS_DIR, f));
    if (baselineFiles.has(f)) {
      if (baseline.files[f] !== h) {
        edited++;
        editedList.push(`${f} (was ${baseline.files[f].slice(0, 12)}, now ${h.slice(0, 12)})`);
      }
    } else {
      added++;
    }
  }
  const removed = [...baselineFiles].filter((f) => !current.includes(f));

  if (edited > 0) {
    report.fail(this, {
      severity: "CRITICAL",
      id: `${id}-EDITED`,
      title: `${edited} applied migration(s) were modified in place`,
      evidence: editedList.join("\n"),
      detail: "Migrations recorded in migration-hashes.json are immutable once applied. Revert the edits and ship the change as a new migration file.",
    });
  } else {
    report.pass(this, `${id}-EDITED`, "No applied migration was modified", `hashes checked: ${current.length}`);
  }

  if (removed.length > 0) {
    report.fail(this, {
      severity: "CRITICAL",
      id: `${id}-REMOVED`,
      title: `${removed.length} recorded migration file(s) were deleted`,
      evidence: removed.join("\n"),
    });
  }

  if (added > 0) {
    report.add(this, {
      status: "PASS",
      severity: "INFO",
      id: `${id}-ADDED`,
      title: `${added} new migration file(s) detected (allowed — must be reviewed)`,
      evidence: current.filter((f) => !baselineFiles.has(f)).join("\n"),
    });
  }
}
